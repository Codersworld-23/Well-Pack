"""Compliance report generation.

Renders a stored scan as an inspection report in two formats:

* **PDF**  - the record an inspector files or serves. Fixed layout, not meant
  to be altered after issue.
* **DOCX** - the same report as an editable document, so an officer can add
  observations, correct a field the OCR misread, or adapt the wording before
  issuing it.

Both are built from the same `_ReportModel`, so the two formats cannot drift
apart in content.
"""

from __future__ import annotations

import io
import logging
from datetime import datetime, timezone
from typing import Any

log = logging.getLogger(__name__)

VERDICT_LABEL = {
    "compliant": "COMPLIANT",
    "partial": "PARTIALLY COMPLIANT",
    "non_compliant": "NON-COMPLIANT",
    "needs_review": "NEEDS REVIEW",
}

# Reserved colour per verdict, in the PDF's RGB space.
VERDICT_RGB = {
    "compliant": (0.11, 0.51, 0.26),
    "partial": (0.72, 0.47, 0.05),
    "non_compliant": (0.70, 0.13, 0.13),
    "needs_review": (0.30, 0.35, 0.45),
}

SEVERITY_ORDER = {"critical": 0, "major": 1, "minor": 2, "info": 3}

FIELD_LABELS = [
    ("commodity_name", "Common / generic name"),
    ("manufacturer", "Manufacturer / packer / importer"),
    ("net_quantity", "Net quantity"),
    ("mrp", "Retail sale price"),
    ("manufacture_date", "Date of manufacture / packing"),
    ("expiry_date", "Best before / use by"),
    ("consumer_care", "Consumer care"),
    ("country_of_origin", "Country of origin"),
    ("batch_number", "Batch / lot number"),
    ("fssai_licence", "FSSAI licence"),
]

DISCLAIMER = (
    "This report is generated by the WellPack Auto-Compliance Check System from "
    "an automated reading of a photographed label. Optical character recognition "
    "and automated analysis can misread a declaration. It is decision-support for "
    "a Legal Metrology officer and is not by itself a determination of "
    "contravention under the Legal Metrology Act, 2009."
)


class _ReportModel:
    """The content of a compliance report, independent of output format."""

    def __init__(self, scan: Any) -> None:
        self.scan_id = str(getattr(scan, "id", "") or "")
        self.created_at = getattr(scan, "created_at", None) or datetime.now(timezone.utc)
        self.product_name = getattr(scan, "product_name", None) or "Unidentified commodity"
        self.verdict = getattr(scan, "verdict", None) or "needs_review"
        self.score = float(getattr(scan, "compliance_score", 0) or 0)
        self.confidence = float(getattr(scan, "confidence", 0) or 0)
        self.hallucination = float(getattr(scan, "hallucination_coefficient", 0) or 0)
        self.engine = getattr(scan, "engine", None) or "unknown"
        self.latency_ms = getattr(scan, "latency_ms", None)
        self.source = getattr(scan, "source", None) or "consumer"
        self.scanned_by = getattr(scan, "scanned_by", None)
        self.fields = dict(getattr(scan, "extracted_fields", None) or {})
        self.physical = dict(getattr(scan, "physical_analysis", None) or {})
        self.violations = sorted(
            list(getattr(scan, "violations", None) or []),
            key=lambda v: SEVERITY_ORDER.get(v.get("severity", "minor"), 4),
        )
        self.citations = list(getattr(scan, "citations", None) or [])
        self.reasoning = getattr(scan, "reasoning", None) or ""
        self.ocr_text = getattr(scan, "ocr_text", None) or ""

    @property
    def verdict_label(self) -> str:
        return VERDICT_LABEL.get(self.verdict, self.verdict.upper())

    @property
    def issued(self) -> str:
        return self.created_at.strftime("%d %B %Y, %H:%M UTC")

    def declarations(self) -> list[tuple[str, str, str]]:
        """(label, value, status) for each mandatory declaration."""
        recovered = set(self.fields.get("recovered_by_llm") or [])
        rows: list[tuple[str, str, str]] = []
        for key, label in FIELD_LABELS:
            value = self.fields.get(key)
            if value in (None, "", []):
                rows.append((label, "Not detected", "Absent"))
            else:
                status = "Recovered from OCR" if key in recovered else "Present"
                rows.append((label, str(value), status))
        return rows

    def quality_notes(self) -> list[str]:
        notes: list[str] = []
        if not self.physical.get("quality_ok", True):
            notes.append(str(self.physical.get("quality_message") or "Capture quality is degraded."))
        count = self.physical.get("uncertain_region_count") or 0
        if count:
            notes.append(
                f"{count} text region(s) were read with low OCR confidence; the "
                "declarations they contain should be confirmed visually."
            )
        if self.fields.get("recovered_by_llm"):
            notes.append(
                "The following declarations were not matched by the pattern extractor "
                "but were found in the OCR text on review: "
                + ", ".join(str(f).replace("_", " ") for f in self.fields["recovered_by_llm"])
                + "."
            )
        if self.hallucination > 0.35:
            notes.append(
                f"Grounding drift is elevated ({self.hallucination:.2f}); verify the "
                "cited clauses against the source rules before acting on this report."
            )
        if not notes:
            notes.append("No capture-quality or grounding concerns were recorded.")
        return notes


