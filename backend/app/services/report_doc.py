# PDF
# ---------------------------------------------------------------------------

def build_pdf(scan: Any) -> bytes:
    """Render the scan as a fixed-layout PDF inspection report."""
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_LEFT
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (
        HRFlowable, KeepTogether, PageBreak, Paragraph, SimpleDocTemplate,
        Spacer, Table, TableStyle,
    )

    model = _ReportModel(scan)
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        leftMargin=18 * mm, rightMargin=18 * mm,
        topMargin=16 * mm, bottomMargin=16 * mm,
        title=f"Compliance report - {model.product_name}",
        author="WellPack Auto-Compliance Check System",
        subject="Legal Metrology (Packaged Commodities) Rules, 2011",
    )

    base = getSampleStyleSheet()
    styles = {
        "title": ParagraphStyle("t", parent=base["Title"], fontSize=17, leading=21,
                                spaceAfter=2, alignment=TA_LEFT),
        "sub": ParagraphStyle("s", parent=base["Normal"], fontSize=9, leading=12,
                              textColor=colors.HexColor("#555555")),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], fontSize=11.5, leading=14,
                             spaceBefore=12, spaceAfter=5,
                             textColor=colors.HexColor("#1a2b45")),
        "body": ParagraphStyle("b", parent=base["Normal"], fontSize=9.2, leading=13),
        "small": ParagraphStyle("sm", parent=base["Normal"], fontSize=7.8, leading=10.5,
                                textColor=colors.HexColor("#444444")),
        "mono": ParagraphStyle("m", parent=base["Normal"], fontName="Courier",
                               fontSize=7.2, leading=9.5),
    }

    def esc(value: Any) -> str:
        return (str(value).replace("&", "&amp;").replace("<", "&lt;")
                .replace(">", "&gt;"))

    story: list[Any] = []

    # --- header ---
    story.append(Paragraph("Legal Metrology Compliance Report", styles["title"]))
    story.append(Paragraph(
        "Packaged Commodities Rules, 2011 &middot; WellPack Auto-Compliance Check System",
        styles["sub"],
    ))
    story.append(Spacer(1, 5))
    story.append(HRFlowable(width="100%", color=colors.HexColor("#c8ced8")))
    story.append(Spacer(1, 9))

    # --- verdict banner ---
    rgb = VERDICT_RGB.get(model.verdict, VERDICT_RGB["needs_review"])
    verdict_colour = colors.Color(*rgb)
    banner = Table(
        [[
            Paragraph(f"<b>{esc(model.verdict_label)}</b>",
                      ParagraphStyle("v", parent=styles["body"], fontSize=14,
                                     leading=17, textColor=colors.white)),
            Paragraph(
                f"<font color='white'>Compliance score <b>{model.score:g}</b>/100<br/>"
                f"Analysis confidence {model.confidence:.0%}</font>",
                ParagraphStyle("vr", parent=styles["small"], textColor=colors.white,
                               fontSize=8.5, leading=11.5),
            ),
        ]],
        colWidths=[105 * mm, 69 * mm],
    )
    banner.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), verdict_colour),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("LEFTPADDING", (0, 0), (-1, -1), 10),
        ("RIGHTPADDING", (0, 0), (-1, -1), 10),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(banner)
    story.append(Spacer(1, 10))

    # --- metadata ---
    meta = [
        ["Scan reference", model.scan_id or "-", "Issued", model.issued],
        ["Commodity", model.product_name[:60], "Captured via", model.source],
        ["Analysis engine", model.engine[:40],
         "Inspector", model.scanned_by or "Not recorded"],
    ]
    meta_table = Table(meta, colWidths=[30 * mm, 57 * mm, 26 * mm, 61 * mm])
    meta_table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 8.2),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.HexColor("#555555")),
        ("TEXTCOLOR", (2, 0), (2, -1), colors.HexColor("#555555")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
    ]))
    story.append(meta_table)

    # --- findings ---
    story.append(Paragraph("1. Findings", styles["h2"]))
    if model.violations:
        rows = [["#", "Severity", "Rule", "Contravention"]]
        for i, v in enumerate(model.violations, 1):
            detail = esc(v.get("message", ""))
            observed, expected = v.get("observed"), v.get("expected")
            if observed:
                detail += f"<br/><font size=7 color='#666666'>Observed: {esc(observed)}</font>"
            if expected:
                detail += f"<br/><font size=7 color='#666666'>Required: {esc(expected)}</font>"
            rows.append([
                str(i),
                esc(v.get("severity", "")).upper(),
                esc(v.get("rule_number", "")),
                Paragraph(detail, styles["small"]),
            ])
        table = Table(rows, colWidths=[8 * mm, 19 * mm, 20 * mm, 127 * mm], repeatRows=1)
        style = [
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef1f5")),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("FONTSIZE", (0, 0), (-1, -1), 7.8),
            ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c8ced8")),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("TOPPADDING", (0, 0), (-1, -1), 4),
            ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ]
        for i, v in enumerate(model.violations, 1):
            if v.get("severity") == "critical":
                style.append(("TEXTCOLOR", (1, i), (1, i), colors.HexColor("#b32121")))
            elif v.get("severity") == "major":
                style.append(("TEXTCOLOR", (1, i), (1, i), colors.HexColor("#b8780d")))
        table.setStyle(TableStyle(style))
        story.append(table)
    else:
        story.append(Paragraph(
            "No contraventions were recorded against the active rule corpus.",
            styles["body"]))

    # --- analyst summary ---
    if model.reasoning:
        story.append(Paragraph("2. Analyst summary", styles["h2"]))
        story.append(Paragraph(esc(model.reasoning), styles["body"]))

    # --- declarations ---
    story.append(Paragraph("3. Declarations read from the label", styles["h2"]))
    decl_rows = [["Declaration", "Value read", "Status"]]
    decl_rows += [[Paragraph(esc(a), styles["small"]),
                   Paragraph(esc(b)[:160], styles["small"]),
                   Paragraph(esc(c), styles["small"])]
                  for a, b, c in model.declarations()]
    decl = Table(decl_rows, colWidths=[52 * mm, 92 * mm, 30 * mm], repeatRows=1)
    decl.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#eef1f5")),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 7.8),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#c8ced8")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("TOPPADDING", (0, 0), (-1, -1), 3.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
    ]))
    story.append(decl)

    # --- legal basis ---
    if model.citations:
        story.append(Paragraph("4. Clauses relied upon", styles["h2"]))
        for c in model.citations[:8]:
            story.append(KeepTogether([
                Paragraph(
                    f"<b>Rule {esc(c.get('rule_number', ''))}</b> &mdash; "
                    f"{esc(c.get('title', ''))} "
                    f"<font size=7 color='#777777'>[{esc(c.get('clause_id', ''))}]</font>",
                    styles["small"]),
                Paragraph(f"<i>{esc(c.get('excerpt', ''))}</i>", styles["small"]),
                Spacer(1, 5),
            ]))

    # --- reviewer notes ---
    story.append(Paragraph("5. Reliability and reviewer notes", styles["h2"]))
    for note in model.quality_notes():
        story.append(Paragraph(f"&bull; {esc(note)}", styles["small"]))

    story.append(Spacer(1, 10))
    story.append(HRFlowable(width="100%", color=colors.HexColor("#c8ced8")))
    story.append(Spacer(1, 5))
    story.append(Paragraph(esc(DISCLAIMER), styles["small"]))
    story.append(Spacer(1, 14))

    sign = Table(
        [["Inspecting officer", "Designation", "Date"],
         ["", "", ""]],
        colWidths=[62 * mm, 62 * mm, 50 * mm], rowHeights=[6 * mm, 14 * mm],
    )
    sign.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, 0), 7.5),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#666666")),
        ("LINEBELOW", (0, 1), (-1, 1), 0.5, colors.HexColor("#888888")),
        ("VALIGN", (0, 0), (-1, -1), "BOTTOM"),
    ]))
    story.append(sign)

    # --- OCR appendix ---
    if model.ocr_text.strip():
        story.append(PageBreak())
        story.append(Paragraph("Appendix A &mdash; Raw OCR transcript", styles["h2"]))
        story.append(Paragraph(
            "Verbatim text read from the label. Findings above are traceable to this "
            "transcript.", styles["small"]))
        story.append(Spacer(1, 5))
        for line in model.ocr_text.splitlines()[:120]:
            if line.strip():
                story.append(Paragraph(esc(line), styles["mono"]))

    def footer(canvas, doc_):
        canvas.saveState()
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(colors.HexColor("#777777"))
        canvas.drawString(18 * mm, 10 * mm, f"WellPack compliance report &middot; {model.scan_id}"
                          .replace("&middot;", "-"))
        canvas.drawRightString(A4[0] - 18 * mm, 10 * mm, f"Page {doc_.page}")
        canvas.restoreState()

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buffer.getvalue()


