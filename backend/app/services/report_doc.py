def build_docx(scan: Any) -> bytes:
    """Render the scan as an editable Word document.

    Same content as the PDF, but as ordinary styled paragraphs and tables so an
    officer can revise wording, correct an OCR misread, or add observations
    before issuing it.
    """
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.shared import Pt, RGBColor

    model = _ReportModel(scan)
    document = Document()

    style = document.styles["Normal"]
    style.font.name = "Calibri"
    style.font.size = Pt(10)

    title = document.add_heading("Legal Metrology Compliance Report", level=0)
    title.alignment = WD_ALIGN_PARAGRAPH.LEFT
    subtitle = document.add_paragraph(
        "Packaged Commodities Rules, 2011 - WellPack Auto-Compliance Check System"
    )
    subtitle.runs[0].font.size = Pt(8.5)
    subtitle.runs[0].font.color.rgb = RGBColor(0x55, 0x55, 0x55)

    verdict_para = document.add_paragraph()
    run = verdict_para.add_run(
        f"{model.verdict_label}  -  score {model.score:g}/100  "
        f"(confidence {model.confidence:.0%})"
    )
    run.bold = True
    run.font.size = Pt(13)
    r, g, b = VERDICT_RGB.get(model.verdict, VERDICT_RGB["needs_review"])
    run.font.color.rgb = RGBColor(int(r * 255), int(g * 255), int(b * 255))

    meta = document.add_table(rows=0, cols=2)
    meta.style = "Light List Accent 1"
    for key, value in [
        ("Scan reference", model.scan_id or "-"),
        ("Issued", model.issued),
        ("Commodity", model.product_name),
        ("Captured via", model.source),
        ("Inspector", model.scanned_by or "Not recorded"),
        ("Analysis engine", model.engine),
    ]:
        cells = meta.add_row().cells
        cells[0].text = key
        cells[1].text = str(value)

    document.add_heading("1. Findings", level=1)
    if model.violations:
        table = document.add_table(rows=1, cols=4)
        table.style = "Table Grid"
        for cell, heading in zip(table.rows[0].cells,
                                 ["#", "Severity", "Rule", "Contravention"]):
            cell.text = heading
            cell.paragraphs[0].runs[0].bold = True
        for i, v in enumerate(model.violations, 1):
            cells = table.add_row().cells
            cells[0].text = str(i)
            cells[1].text = str(v.get("severity", "")).upper()
            cells[2].text = str(v.get("rule_number", ""))
            detail = str(v.get("message", ""))
            if v.get("observed"):
                detail += f"\nObserved: {v['observed']}"
            if v.get("expected"):
                detail += f"\nRequired: {v['expected']}"
            cells[3].text = detail
    else:
        document.add_paragraph(
            "No contraventions were recorded against the active rule corpus."
        )

    if model.reasoning:
        document.add_heading("2. Analyst summary", level=1)
        document.add_paragraph(model.reasoning)

    document.add_heading("3. Declarations read from the label", level=1)
    decl = document.add_table(rows=1, cols=3)
    decl.style = "Table Grid"
    for cell, heading in zip(decl.rows[0].cells, ["Declaration", "Value read", "Status"]):
        cell.text = heading
        cell.paragraphs[0].runs[0].bold = True
    for label, value, status in model.declarations():
        cells = decl.add_row().cells
        cells[0].text = label
        cells[1].text = value[:200]
        cells[2].text = status

    if model.citations:
        document.add_heading("4. Clauses relied upon", level=1)
        for c in model.citations[:8]:
            para = document.add_paragraph()
            head = para.add_run(
                f"Rule {c.get('rule_number', '')} - {c.get('title', '')} "
                f"[{c.get('clause_id', '')}]"
            )
            head.bold = True
            excerpt = document.add_paragraph(str(c.get("excerpt", "")))
            excerpt.runs[0].italic = True
            excerpt.runs[0].font.size = Pt(8.5)

    document.add_heading("5. Reliability and reviewer notes", level=1)
    for note in model.quality_notes():
        document.add_paragraph(note, style="List Bullet")

    document.add_heading("6. Officer observations", level=1)
    placeholder = document.add_paragraph(
        "[Add observations, corrections to any misread declaration, and the action "
        "taken here before issuing this report.]"
    )
    placeholder.runs[0].italic = True
    placeholder.runs[0].font.color.rgb = RGBColor(0x88, 0x88, 0x88)

    document.add_paragraph()
    disclaimer = document.add_paragraph(DISCLAIMER)
    disclaimer.runs[0].font.size = Pt(8)
    disclaimer.runs[0].font.color.rgb = RGBColor(0x55, 0x55, 0x55)

    document.add_paragraph()
    sign = document.add_table(rows=2, cols=3)
    sign.style = "Table Grid"
    for cell, heading in zip(sign.rows[0].cells,
                             ["Inspecting officer", "Designation", "Date"]):
        cell.text = heading
        cell.paragraphs[0].runs[0].bold = True
    for cell in sign.rows[1].cells:
        cell.text = " "

    if model.ocr_text.strip():
        document.add_page_break()
        document.add_heading("Appendix A - Raw OCR transcript", level=1)
        note = document.add_paragraph(
            "Verbatim text read from the label. Findings above are traceable to "
            "this transcript."
        )
        note.runs[0].font.size = Pt(8.5)
        mono = document.add_paragraph()
        run = mono.add_run(model.ocr_text[:6000])
        run.font.name = "Consolas"
        run.font.size = Pt(8)

    buffer = io.BytesIO()
    document.save(buffer)
    return buffer.getvalue()


def filename_for(scan: Any, extension: str) -> str:
    """A stable, filesystem-safe download name for a scan's report."""
    import re

    model = _ReportModel(scan)
    slug = re.sub(r"[^A-Za-z0-9]+", "-", model.product_name).strip("-").lower()[:40]
    stamp = model.created_at.strftime("%Y%m%d")
    return f"wellpack-compliance-{slug or 'report'}-{stamp}.{extension}"
